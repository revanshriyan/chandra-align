"""Scoped AI-watermark hygiene test.

Standing rule: no AI watermark / AI-attribution text in code, commits,
docs or deliverables (model-name generation claims, co-author trailers,
"as an AI" self-identification).

Why this test is an AST scan, not a grep (Integrity Auditor direction):
a blanket grep over the tree is not feasible -- it flags legitimate
evidence lines (provenance footers, scan reports, audit-trail mentions)
and cannot tell a docstring or comment from code that ships. This test
therefore scans only string literals in *executable* statements of
``*.py`` files:

* module / class / function docstrings are excluded (they document,
  they do not execute);
* comments are invisible to ``ast`` and are out of scope by
  construction (a watermark hidden in a comment is a review matter,
  not something this scan can see);
* the one file this test cannot scan is itself: the denylist below
  necessarily contains the banned phrases as literals, so this file is
  path-excluded (see ``PATH_EXCLUSIONS``). Any other file containing
  them fails.

A match is a violation unless it is an explicit allow-list entry
(``ALLOWLIST``): a (path, distinctive-substring, reason) triple.
Allow-list entries name the legitimate provenance line, so a future
edit that moves the line does not silently break the test, while a
new "Generated by ..." line anywhere else still fails.

Scope notes (deliberate, not oversights):
* Only ``*.py`` files are scanned. Docs / CSV / JSON evidence lines
  are out of scope for this test -- that is exactly the blanket-grep
  failure mode the Auditor rejected.
* Signature emojis are not scanned: an emoji alone is not evidence of
  an AI watermark, and every emoji watermark observed in practice also
  carries a banned phrase above, which this test does catch.
"""

import ast
import re
from pathlib import Path

# (regex, what it bans). Case-insensitive; "generated by" is generic on
# purpose: any generation claim in code must be an allow-listed script
# provenance line, never a model name.
DENYLIST = [
    (re.compile(r"generated\s+by\b", re.IGNORECASE),
     "generation claim (must be an allow-listed script provenance line)"),
    (re.compile(r"co-authored-by\b", re.IGNORECASE),
     "AI-tool co-author trailer"),
    (re.compile(r"created\s+by\s+(Muse|AI|Claude|ChatGPT|GPT-?\d*|Copilot)\b",
                re.IGNORECASE),
     "AI creation claim"),
    (re.compile(r"written\s+by\s+(Muse|AI|Claude|ChatGPT|GPT-?\d*|Copilot)\b",
                re.IGNORECASE),
     "AI authorship claim"),
    (re.compile(r"as\s+an\s+AI\b", re.IGNORECASE),
     "AI self-identification"),
    (re.compile(r"powered\s+by\s+(Muse|AI|Claude|ChatGPT|GPT-?\d*|Copilot)\b",
                re.IGNORECASE),
     "AI-powered claim"),
    (re.compile(r"\bI\s+am\s+(Muse|an\s+AI)\b", re.IGNORECASE),
     "AI self-identification"),
]

# (relative path, distinctive substring of the legitimate literal, reason).
# These are the only executable-string matches on the tree at the time
# this test was written; each names its generating script, not a model.
ALLOWLIST = [
    ("scripts/generate_results_table.py",
     "Generated by `scripts/generate_results_table.py`",
     "provenance footer of the results-table generator, naming the script"),
    ("scripts/freeze_evidence.py",
     "Re-generated by scripts/freeze_evidence.py",
     "evidence-freeze header written by the freeze script, naming the script"),
]

# (relative path, reason). The denylist and allow-list literals below
# are executable statements in this file, so it cannot scan itself.
PATH_EXCLUSIONS = {
    "tests/test_no_ai_watermark.py":
        "this file defines the denylist/allow-list, so it contains the "
        "banned phrases as literals by necessity",
}

SKIP_DIRS = {".git", "__pycache__", ".venv", "venv", "node_modules"}


def _docstring_ids(tree):
    """Ids of string constants that are docstrings (first statement of
    a module / class / function body)."""
    ids = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                             ast.AsyncFunctionDef)):
            if (node.body and isinstance(node.body[0], ast.Expr)
                    and isinstance(node.body[0].value, ast.Constant)
                    and isinstance(node.body[0].value.value, str)):
                ids.add(id(node.body[0].value))
    return ids


def scan_source(source, rel_path):
    """Return violation strings for one file's source text."""
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        # Fail closed: an unparsable file cannot be proven clean.
        return [f"{rel_path}:{exc.lineno}: unparsable ({exc.msg})"]
    docstrings = _docstring_ids(tree)
    violations = []
    for node in ast.walk(tree):
        if (isinstance(node, ast.Constant)
                and isinstance(node.value, str)
                and id(node) not in docstrings):
            for pattern, desc in DENYLIST:
                if pattern.search(node.value):
                    if any(rel_path == path and sub in node.value
                           for path, sub, _ in ALLOWLIST):
                        break
                    violations.append(
                        f"{rel_path}:{node.lineno}: {desc}: "
                        f"{node.value[:100]!r}")
                    break
    return violations


def scan_tree(root):
    """Return violation strings for every *.py file under root."""
    root = Path(root)
    violations = []
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root).as_posix()
        if any(part in SKIP_DIRS for part in path.relative_to(root).parts):
            continue
        if rel in PATH_EXCLUSIONS:
            continue
        try:
            source = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            violations.append(f"{rel}: unreadable ({exc})")
            continue
        violations.extend(scan_source(source, rel))
    return violations


def test_no_ai_watermark_in_executable_strings():
    root = Path(__file__).resolve().parents[1]
    violations = scan_tree(root)
    assert not violations, (
        "AI-watermark/attribution text in executable string literals:\n"
        + "\n".join(violations)
        + "\n(If a hit is legitimate script provenance, add it to "
        "ALLOWLIST with a reason -- do not weaken DENYLIST.)"
    )


def test_scanner_flags_executable_violation():
    violations = scan_source('MSG = "Generated by Muse"\n', "probe.py")
    assert len(violations) == 1
    assert violations[0].startswith("probe.py:1:")


def test_scanner_ignores_docstrings():
    assert scan_source('"""Generated by Muse"""\n', "probe.py") == []
    code = ('def f():\n'
            '    """Generated by Muse"""\n'
            '    return 1\n')
    assert scan_source(code, "probe.py") == []


def test_scanner_allowlists_script_provenance():
    code = ('lines.append("Generated by `scripts/generate_results_table.py`. ")\n')
    assert scan_source(code, "scripts/generate_results_table.py") == []
    # Same literal anywhere else is still a violation.
    assert scan_source(code, "scripts/other.py") != []
